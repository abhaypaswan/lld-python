#!/usr/bin/env python3
"""Generate catalog.json and refresh the problem table in README.md.

catalog.json is the single artifact goatengineer.com reads. Everything in it is
derived from the per-problem meta.json files, so the way to change the catalog
is to change a meta.json and re-run this script -- never to hand-edit the
output.

The README table lives between two HTML comment markers. Anything outside them
is left alone, so the rest of the README stays hand-written.

It also writes docs/patterns.md, the cross-cutting index: which problems
exercise which design pattern. That is derived from the same meta.json files,
so the only hand-written part is each pattern's explanation, which lives in
scripts/patterns_reference.py.

Usage:
    python3 scripts/build_catalog.py           # write every generated file
    python3 scripts/build_catalog.py --check   # fail if any is out of date
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from patterns_reference import PATTERN_REFERENCE  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parent.parent
PROBLEMS_DIR = REPO_ROOT / "problems"
CATALOG_PATH = REPO_ROOT / "catalog.json"
README_PATH = REPO_ROOT / "README.md"
PATTERNS_DOC_PATH = REPO_ROOT / "docs" / "patterns.md"

TABLE_START = "<!-- BEGIN PROBLEM TABLE (generated by scripts/build_catalog.py) -->"
TABLE_END = "<!-- END PROBLEM TABLE -->"

DIFFICULTY_ORDER = {"easy": 0, "medium": 1, "hard": 2}
DIFFICULTY_BADGE = {"easy": "🟢 Easy", "medium": "🟡 Medium", "hard": "🔴 Hard"}

# Pattern slugs are kebab-case in meta.json because they are machine keys. These
# are the names humans actually use for them.
PATTERN_NAMES = {
    "abstract-factory": "Abstract Factory",
    "adapter": "Adapter",
    "builder": "Builder",
    "chain-of-responsibility": "Chain of Responsibility",
    "command": "Command",
    "composite": "Composite",
    "decorator": "Decorator",
    "facade": "Facade",
    "factory-method": "Factory Method",
    "iterator": "Iterator",
    "mediator": "Mediator",
    "memento": "Memento",
    "observer": "Observer",
    "proxy": "Proxy",
    "repository": "Repository",
    "singleton": "Singleton",
    "state": "State",
    "strategy": "Strategy",
    "template-method": "Template Method",
    "visitor": "Visitor",
}


def load_problems() -> list[dict]:
    """Read every problems/<slug>/meta.json, sorted easy to hard then by title."""
    problems = []
    for directory in sorted(d for d in PROBLEMS_DIR.iterdir() if d.is_dir()):
        meta_path = directory / "meta.json"
        if not meta_path.is_file():
            print(f"  skipping {directory.name}: no meta.json", file=sys.stderr)
            continue
        problems.append(json.loads(meta_path.read_text(encoding="utf-8")))

    problems.sort(key=lambda p: (DIFFICULTY_ORDER.get(p.get("difficulty", ""), 99), p["title"]))
    return problems


def render_catalog(problems: list[dict]) -> str:
    """Build the JSON document that goatengineer.com consumes."""
    catalog = {
        "$schema": "./schema/problem.schema.json",
        "version": 1,
        "source": "https://github.com/abhaypaswan/lld-python",
        "count": len(problems),
        "patterns": sorted({p for prob in problems for p in prob.get("patterns", [])}),
        "tags": sorted({t for prob in problems for t in prob.get("tags", [])}),
        "problems": [dict(prob, path=f"problems/{prob['slug']}") for prob in problems],
    }
    return json.dumps(catalog, indent=2, ensure_ascii=False) + "\n"


def render_table(problems: list[dict]) -> str:
    """Build the markdown table that goes between the README markers."""
    lines = [
        TABLE_START,
        "",
        "| # | Problem | Difficulty | Design Patterns | Time |",
        "| --- | --- | --- | --- | --- |",
    ]

    for index, problem in enumerate(problems, start=1):
        slug = problem["slug"]
        patterns = ", ".join(PATTERN_NAMES.get(p, p) for p in problem.get("patterns", []))
        difficulty = DIFFICULTY_BADGE.get(
            problem.get("difficulty", ""), problem.get("difficulty", "")
        )
        minutes = problem.get("estimatedMinutes")
        time = f"{minutes} min" if minutes else "—"
        lines.append(
            f"| {index} | [{problem['title']}](problems/{slug}/) "
            f"| {difficulty} | {patterns} | {time} |"
        )

    lines.extend(["", TABLE_END])
    return "\n".join(lines)


def _by_title(problem: dict) -> str:
    """Sort case-insensitively, so "Design a Parking Lot" and "Design Chess"
    interleave alphabetically rather than splitting into two blocks."""
    return problem["title"].lower()


def render_patterns_doc(problems: list[dict]) -> str:
    """Build docs/patterns.md: each pattern, and the problems that use it."""
    by_pattern: dict[str, list[dict]] = {}
    for problem in problems:
        for pattern in problem.get("patterns", []):
            by_pattern.setdefault(pattern, []).append(problem)

    lines = [
        "# Design Patterns by Problem",
        "",
        "> Generated by `scripts/build_catalog.py`. Do not edit by hand.",
        "",
        "Every pattern below is used by at least one problem in this repository,",
        "in code you can run. Each entry says what the pattern is for, the question",
        "in a problem that makes you reach for it, and the mistake it tends to",
        "attract — then lists where to go and read one.",
        "",
        f"**{len(by_pattern)} patterns across {len(problems)} problems.**",
        "",
        "## At a glance",
        "",
        "| Pattern | Problems |",
        "| --- | --- |",
    ]

    for pattern in sorted(by_pattern):
        links = ", ".join(
            f"[{p['title']}](../problems/{p['slug']}/)"
            for p in sorted(by_pattern[pattern], key=_by_title)
        )
        lines.append(f"| **{PATTERN_NAMES.get(pattern, pattern)}** | {links} |")

    lines.append("")

    for pattern in sorted(by_pattern):
        reference = PATTERN_REFERENCE.get(pattern, {})
        lines.extend(["---", "", f"## {PATTERN_NAMES.get(pattern, pattern)}", ""])

        if reference.get("intent"):
            lines.extend([reference["intent"], ""])
        if reference.get("question"):
            lines.extend([f"**Reach for it when:** {reference['question']}", ""])
        if reference.get("mistake"):
            lines.extend([f"**The usual mistake:** {reference['mistake']}", ""])

        lines.append("**Worked examples:**")
        lines.append("")
        for problem in sorted(by_pattern[pattern], key=_by_title):
            others = [
                PATTERN_NAMES.get(other, other)
                for other in problem.get("patterns", [])
                if other != pattern
            ]
            alongside = f" — alongside {', '.join(others)}" if others else ""
            lines.append(
                f"- [**{problem['title']}**](../problems/{problem['slug']}/) "
                f"({DIFFICULTY_BADGE.get(problem.get('difficulty', ''), '')}){alongside}  "
            )
            lines.append(f"  {problem['summary']}")
        lines.append("")

    return "\n".join(lines)


def splice_table(readme: str, table: str) -> str:
    """Replace whatever sits between the markers with the freshly built table."""
    start = readme.find(TABLE_START)
    end = readme.find(TABLE_END)

    if start == -1 or end == -1:
        raise SystemExit(
            f"README.md is missing the table markers.\n"
            f"Add these two lines where the table should go:\n"
            f"  {TABLE_START}\n  {TABLE_END}"
        )
    if end < start:
        raise SystemExit("README.md has the table markers in the wrong order.")

    return readme[:start] + table + readme[end + len(TABLE_END) :]


def main(argv: list[str]) -> int:
    check_only = "--check" in argv

    problems = load_problems()
    if not problems:
        print("No problems with a meta.json were found.", file=sys.stderr)
        return 1

    generated = {
        CATALOG_PATH: render_catalog(problems),
        README_PATH: splice_table(README_PATH.read_text(encoding="utf-8"), render_table(problems)),
        PATTERNS_DOC_PATH: render_patterns_doc(problems),
    }

    if check_only:
        stale = [
            path.relative_to(REPO_ROOT)
            for path, content in generated.items()
            if not path.is_file() or path.read_text(encoding="utf-8") != content
        ]
        if stale:
            print(
                f"Out of date: {', '.join(str(p) for p in stale)}.\n"
                f"Run: python3 scripts/build_catalog.py",
                file=sys.stderr,
            )
            return 1

        print(f"Generated files are up to date ({len(problems)} problems).")
        return 0

    for path, content in generated.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")

    names = ", ".join(str(path.relative_to(REPO_ROOT)) for path in generated)
    print(f"Wrote {names} ({len(problems)} problems).")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
